import type { PersonType } from "../model/types";

// Названия и описания — рабочие заглушки. Настоящая типология — у Мастера.
const names: [string, string][] = [
  ["Исследователь", "Любопытство и поиск смыслов"],
  ["Хранитель", "Надёжность и забота о близких"],
  ["Созидатель", "Идеи, которые становятся делом"],
  ["Странник", "Свобода и движение"],
  ["Мудрец", "Глубина и наблюдение"],
  ["Воин", "Решительность и защита"],
  ["Целитель", "Чуткость и восстановление"],
  ["Творец", "Образность и вдохновение"],
  ["Строитель", "Порядок и опора"],
  ["Проводник", "Связи между людьми"],
  ["Созерцатель", "Тишина и присутствие"],
  ["Огонёк", "Энергия и заразительная радость"],
];

const personTypes: PersonType[] = names.map(([name, short], i) => ({
  id: `t${i + 1}`,
  number: i + 1,
  name,
  short,
  description: `${short}. Подробное описание типа «${name}» Мастер добавит в кабинете администратора: сильные стороны, на что обратить внимание и как этому типу лучше выстраивать практику в разные стихии.`,
}));

export function getPersonTypes(): PersonType[] {
  return personTypes;
}

export function getPersonType(id: string): PersonType | undefined {
  return personTypes.find((t) => t.id === id);
}
