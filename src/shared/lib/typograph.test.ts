import { describe, expect, it } from "vitest";

import { typograph } from "./typograph";

const nbsp = " ";

describe("Неразрывные пробелы в текстах", () => {
  it("цифра привязана к следующему слову, тире — к предыдущему", () => {
    expect(typograph("5 стихий — 5 сезонов")).toBe(`5${nbsp}стихий${nbsp}— 5${nbsp}сезонов`);
  });

  it("предлог и союз привязаны к следующему слову", () => {
    expect(typograph("путь в программе и практики")).toBe(`путь в${nbsp}программе и${nbsp}практики`);
  });

  it("два коротких слова подряд привязаны оба", () => {
    expect(typograph("а с ними")).toBe(`а${nbsp}с${nbsp}ними`);
  });

  it("слово из трёх букв остаётся на строке", () => {
    expect(typograph("тест или практика")).toBe("тест или практика");
  });

  it("длинные слова не трогает", () => {
    expect(typograph("Короткий тест определит")).toBe("Короткий тест определит");
  });
});
