const NBSP = " ";

/**
 * Неразрывные пробелы, чтобы в конце строки не висели цифры, предлоги и союзы,
 * а строка не начиналась с тире. docs/design-guide.md, раздел «Тексты».
 * Слово из одной-двух букв или число привязывается к следующему слову, тире — к предыдущему.
 */
export function typograph(text: string): string {
  return text
    .replace(/(^|[\s«„(])([а-яёa-z]{1,2}|\d+) /gi, `$1$2${NBSP}`)
    .replace(/(^|[\s«„(])([а-яёa-z]{1,2}|\d+) /gi, `$1$2${NBSP}`)
    .replace(/ (—|–)/g, `${NBSP}$1`);
}
