/** Запись журнала: день и текст заметки к «Мышлению по навигатору». */
export type JournalNote = { day: string; text: string };

const months = [
  "января",
  "февраля",
  "марта",
  "апреля",
  "мая",
  "июня",
  "июля",
  "августа",
  "сентября",
  "октября",
  "ноября",
  "декабря",
];

/** «2026-11-22» → «22 ноября 2026». */
export function journalDate(day: string): string {
  const [year, month, date] = day.split("-").map(Number);
  return `${date} ${months[month - 1]} ${year}`;
}

